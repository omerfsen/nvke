#!/usr/bin/env python3
"""Write docs/variables.md from the roles' meta/argument_specs.yml."""
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
ROLES = [
    ("nvke", ["bootstrap_host", "node", "site"]),
    ("node_image", ["main"]),
    ("bgp_peer", ["main"]),
    ("libvirt_vm", ["main"]),
    ("gpu_passthrough", ["main"]),
    ("gpu_operator", ["main"]),
]


def fmt_default(value):
    if value is None:
        return ""
    if value == "":
        return '`""`'
    if isinstance(value, (dict, list)) and not value:
        return "`{}`" if isinstance(value, dict) else "`[]`"
    return f"`{value}`"


def fmt_text(text):
    text = " ".join(text if isinstance(text, list) else [text])
    text = re.sub(r"[CO]\(([^)]*)\)", r"`\1`", text)
    return text.replace("|", "\\|")


def main():
    out = [
        "# Variables",
        "",
        "Generated by `make docs` from the roles' `meta/argument_specs.yml`;",
        "`ansible-doc -t role omerfsen.nvke.<role>` shows the same.",
        "",
    ]
    for role, entry_points in ROLES:
        spec = yaml.safe_load((ROOT / "roles" / role / "meta" / "argument_specs.yml").read_text())
        out += [f"## omerfsen.nvke.{role}", ""]
        seen = set()
        for ep in entry_points:
            entry = spec["argument_specs"][ep]
            if len(entry_points) > 1:
                out += [f"### Entry point `{ep}`", "", entry["short_description"], ""]
            out += ["| Variable | Type | Default | Description |", "|---|---|---|---|"]
            for name, opt in entry["options"].items():
                note = " (also in an earlier entry point)" if name in seen else ""
                seen.add(name)
                required = "**Required.** " if opt.get("required") else ""
                out.append(
                    f"| `{name}` | {opt.get('type', '')} | {fmt_default(opt.get('default'))} "
                    f"| {required}{fmt_text(opt.get('description', ''))}{note} |"
                )
            out.append("")
    (ROOT / "docs" / "variables.md").write_text("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
